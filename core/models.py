@dataclass(slots=True)
class OptionContract:
    """Represents a single option contract."""

    symbol: str
    underlying: str
    strike: float
    expiry: datetime
    option_type: str  # "CALL" | "PUT"
    multiplier: int = 100

    # Greeks (updated in real-time)
    delta: float = 0.0
    gamma: float = 0.0
    vega: float = 0.0
    theta: float = 0.0
    rho: float = 0.0
    implied_vol: float = 0.0

    # Market data
    bid: float = 0.0
    ask: float = 0.0
    last: float = 0.0
    volume: int = 0
    open_interest: int = 0

    @property
    def mid_price(self) -> float:
        return (self.bid + self.ask) / 2 if self.bid and self.ask else self.last

    @property
    def days_to_expiry(self) -> float:
        return max(0, (self.expiry - datetime.utcnow()).total_seconds() / 86400)


@dataclass(slots=True)
class GreeksExposure:
    """Aggregated Greeks exposure for a portfolio."""

    delta: float = 0.0
    gamma: float = 0.0
    vega: float = 0.0
    theta: float = 0.0
    rho: float = 0.0
